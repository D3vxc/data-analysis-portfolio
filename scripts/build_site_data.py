import csv, random
# Compact per-flow scores for the dissertation scroll visual. 6,000 flows sampled from the test
# half, stratified so the attack rate matches. Four display groups, chosen to tell the story:
# normal traffic (whose flag rate is the false alarm rate), the two biggest attack families,
# and everything else.
fam_names = json.loads((ROOT / "08-hybrid-intrusion-detection" / "results" / "families.json").read_text())
flows = list(csv.DictReader(open(ROOT / "08-hybrid-intrusion-detection" / "results" / "test_scores.csv")))
random.Random(7).shuffle(flows)
flows = flows[:6000]
GROUPS = ["Normal traffic", "Generic", "Exploits", "Other attacks"]
def group(row):
    name = fam_names[int(row["family"])]
    if name == "Normal": return 0
    if name == "Generic": return 1
    if name == "Exploits": return 2
    return 3
ids_compact = {
    "score": [round(float(r["hybrid"]) * 1000) for r in flows],
    "anom": [round(float(r["anomaly"]) * 1000) for r in flows],
    "y": "".join(r["attack"] for r in flows),
    "grp": "".join(str(group(r)) for r in flows),
    "grps": GROUPS,
}
out3 = ROOT / "docs" / "data" / "ids-test.js"
out3.write_text("// Generated by scripts/build_site_data.py: hybrid IDS test-set scores (no raw features).\n"
                "window.IDS_TEST = " + json.dumps(ids_compact, separators=(",", ":")) + ";\n")
print(f"wrote {out3.relative_to(ROOT)} ({out3.stat().st_size:,} bytes)")
