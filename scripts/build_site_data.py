"""Collect each project's results/summary.json into docs/data/site-data.js for the website.

Run from the repo root after re-running any notebook:
    python scripts/build_site_data.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
load = lambda folder: json.loads((ROOT / folder / "results" / "summary.json").read_text())

churn = load("04-telecom-customer-churn")
ab = load("05-mobile-game-ab-test")
deliv = load("06-ecommerce-late-deliveries")
retail = load("01-uk-online-retail")
house = load("02-uk-house-prices")
nsl = load("03-network-traffic-eda")

site = {
    "churn": {
        "kpis": churn["kpis"], "segment": churn["segment"], "targeting": churn["targeting"],
        "by_contract": churn["by_contract"], "by_tenure": churn["by_tenure"], "deciles": churn["deciles"],
    },
    "ab": {
        "srm": ab["srm"], "tests": ab["tests"], "prob": ab["prob_30_better_pct"],
        "retention": ab["retention"], "checks": ab["checks"],
    },
    "deliveries": {"headline": deliv["headline"], "by_band": deliv["by_band"], "monthly": deliv["monthly"], "states": deliv["states"]},
    "retail": {k: retail[k] for k in ["kpis", "monthly", "rfm_segments", "cleaning_log"]},
    "house": {k: house[k] for k in ["series", "yoy", "episodes", "downturns"]},
    "nsl": {k: nsl[k] for k in ["recall_by_category_pct", "recall_seen_pct", "recall_unseen_pct", "balance", "scores", "unseen_share_pct"]},
}
out = ROOT / "docs" / "data" / "site-data.js"
out.write_text("// Generated by scripts/build_site_data.py from each project's results/summary.json. Do not edit by hand.\n"
               "window.SITE_DATA = " + json.dumps(site, separators=(",", ":")) + ";\n")
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size:,} bytes)")
